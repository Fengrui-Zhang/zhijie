export function palaceSymbolism(analysis: CharacterAnalysis): { title: string; meaning: string; groups: SymbolismGroup[] } {
  const { target, selection } = analysis;
  if (target.kind === 'flow') {
    const periods: Record<string, [string, string]> = {
      dayun: ['大运', '对应十年左右的阶段背景，取这一阶段的环境、活动范围与人生主题。'],
      liunian: ['流年', '对应所选年份，取当年的经历、往来与阶段性变化。'],
      liuyue: ['流月', '对应所选月份，取年内事务的推进节奏与近期环境。'],
      liuri: ['流日', '对应所选日期，取当日事务、接触与短期变化。'],
    };
    const [title, meaning] = periods[target.key] ?? [target.title, '对应当前选中的时间层次。'];
    return { title: `${title} · 时间层次`, meaning, groups: [{ label: '当前落点', text: `${target.subtitle || target.ganZhi}，${selection.kind === 'hidden' ? `藏干${analysis.stem}位于${target.ganZhi[1]}中。` : `当前查看${analysis.location}。`}` }] };
  }
  const isStem = selection.kind === 'stem';
  const palaces: Record<string, { title: string; meaning: string; people: string; affairs: string; focus: string }> = {
    年柱: { title: '祖上父母宫', meaning: '年柱取出身、祖业与远方之象，是家族背景和早年环境的落点。', people: '祖辈、父母、家族及远方的人。', affairs: '祖业、出生地、童年经历、家族传统与社会大环境。', focus: isStem ? '年干偏向家族外显的状态，也常用于看父亲与祖上的象。' : '年支偏向家族根基、承载与居处，也联系母亲的宫位象。' },
    月柱: { title: '父母同辈宫', meaning: '月柱取父母、同辈与社会生活之象，联系求学、工作和主要交往环境。', people: '父母、兄弟姐妹、领导、同事与社会同辈。', affairs: '工作平台、社会关系、成长环境与事业活动。', focus: isStem ? '月干偏向外在角色、工作往来与社会关系的显现。' : '月支兼为月令，联系季节气候、成长根基与母亲的宫位象。' },
    日柱: { title: isStem ? '日主 · 自身' : '夫妻宫', meaning: isStem ? '日干代表命主自身，是全盘十神关系的参照点。' : '日支为夫妻宫，取配偶、亲密关系与核心小家庭之象。', people: isStem ? '自身，也联系与自己平等往来的同辈。' : '配偶、伴侣，以及共同生活的亲近之人。', affairs: isStem ? '自身意愿、行动方式与自我表达。' : '婚姻生活、家庭归属、居处与内在感受。', focus: isStem ? '从此处出发观察其他字与自身的生克关系。' : '日支贴近日主，是观察亲密关系和家庭氛围的位置。' },
    时柱: { title: '子女成果宫', meaning: '时柱取子女、未来与成果之象，联系所培养、创造和传承的事物。', people: '子女、晚辈、下属、学生与继承者。', affairs: '作品、事业成果、未来规划、晚年生活与传承。', focus: isStem ? '时干偏向向外延伸的行动、成果表达与晚辈往来。' : '时支偏向成果落点、子女生活与晚年的归宿。' },
  };
  const palace = palaces[target.title];
  if (!palace) return { title: target.title, meaning: `当前字位于${target.title}。`, groups: [] };
  return { title: palace.title, meaning: palace.meaning, groups: [
    { label: '人物关系', text: palace.people }, { label: '生活领域', text: palace.affairs },
    { label: selection.kind === 'hidden' ? '藏干落点' : '当前落点', text: `${selection.kind === 'hidden' ? `${analysis.stem}藏于${target.title}${analysis.branch}中，承接这一地支的宫位象。` : ''}${palace.focus}` },
  ] };
}
